<div><h2>Facts</h2>

    * Een 1 fase omvormer kan ook op een 3-fase aansluiting worden aangesloten. De netbeheerder adviseert daarin op welke fase uw zonnepanelen dan aangesloten dienen te worden (om dat je volgens mij letterlijk dan 3 stengels je huis in krijgt, en op 1 daarvan moeten dan de panelen).

    * Plaats omvormer: niet al te stoffig is en warmte goed weg kan. Een koele garage, daarentegen, is de perfecte plek.

    * Het vermogen van de omvormer mag iets lager liggen dan het vermogen van de zonnepanelen, omdat het piekvermogen alleen in de allerbeste omstandigheden wordt opgewekt.

    * Alle stroom die boven het AC uitgangsvermogen wordt opgewekt wordt afgetopt en 'verdwijnt'. (ik: dus stel je omvormer is 4000, en je hebt 3000 panelen, wekt 50.000 op, dan krijg je nog steeds 4000).

    * Omvormer wordt ook inverter genoemd.

    * Hybride-omvoromer is een die ook een batterij ondersteunt

    * Je hoeft niet direct een batterij aan te sluiten bij installatie van een hybride omvormer, dit kan ook later.

    * Kabels van zonnepanelen tot omvormer liever: niet  langer dan 15 tot 20 meter. Zo blijven de kabelverliezen ruim onder de 1%.
    * Kabels van omvormer naar de meterkast bij voorkeur ook niet langer dan 20 meter te zijn.

    * De opbrengst van de zonnepanelen-installatie mag bij een PV-verdeler maximaal 3680 Watt bedragen.
    Wouter: dus een omvormer groter dan 3680 watt uitgang heeft denk geen zin.

    * pv -verdeler moet niet achter een aardlekschakelaar. Wouter: Betekend dus een (kleine) aan[assing in de meterkast,

    * Gebruik je geen pv-verdeler, en gaat de omvormer (via werkschakelaar eventueel) direct naar de meterkast, dan is 1 aardleksckkelaar okay.

    * Er zijn tegenwoordig ook aardlekautomaten. Geen idee nog of we dit moeten of kunnen gebruiken. 3 fase zal handig zijn voor auto lading

    * Er is een nieuwe omvormer van SMA 'sma tripower smart energy'. Dit is ook een hybride, en is interessant.
    want sma heeft shadefixing - geen optimzers nodig.  Sluit aan op een batterij van niet SMA-merken. SMA heeft geen eigen batterij.

</div>
